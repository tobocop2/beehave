#!/bin/sh
# Usage: mkprojects.sh [config folder]
# Writes one obee project file for each row of repos.tsv, and one for the report. Run it after any change to repos.tsv.
# A file that a person wrote (no GENERATED marker on the first line) is never replaced.
set -eu
. "$(dirname "$0")/lib.sh"
cfg=${1:-${OBEE_CONFIG:-$HOME/.config/obee}}/projects
mkdir -p "$cfg"
tab=$(printf '\t')

put() { # <file> reads the new text on stdin
    if [ -f "$1" ] && ! head -n 1 "$1" | grep -q '^# GENERATED by mkprojects.sh'; then echo "kept $1: not generated" >&2; cat > /dev/null; return 0; fi
    cat > "$1"
    echo "wrote $1"
}

while IFS="$tab" read -r name slug base gate <&3; do
    case "$name" in "" | \#*) continue ;; esac
    valid "$name" || { echo "bad name $name" >&2; exit 2; }
    case "$gate" in *\"* | *\\*) echo "the gate of $name holds a quote or a backslash" >&2; exit 2 ;; esac
    printf '# GENERATED by mkprojects.sh from repos.tsv. Do not edit.\nproject(\n    repo = "%s",\n    forge = "github",\n    base_branch = "%s",\n    gate = "%s",\n    test_report = "reports/*.xml",\n)\n' "$slug" "$base" "$gate" | put "$cfg/$name.star"
done 3< "$UPKEEP_HOME/repos.tsv"

printf '# GENERATED by mkprojects.sh. Do not edit.\nproject(\n    source = "%s",\n    base_branch = "main",\n    gate = "true",\n    test_report = "reports/*.xml",\n)\n' "$UPKEEP_HOME" | put "$cfg/upkeep.star"
